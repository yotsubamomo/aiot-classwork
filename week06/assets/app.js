/* DIC-02 Feature Selection Explorer - DOM, events and Chart.js. All numbers come from MODEL_DATA. */
(function () {
  'use strict';
  const DATA = window.MODEL_DATA;
  const C = window.Core;
  const SCHEMES = DATA.schemes.map((s) => s.name);
  const ALL = '__all__';
  const POINT_STYLES = ['circle', 'rect', 'triangle', 'rectRot', 'triangle'];
  const POINT_ROTATION = [0, 0, 0, 0, 180];          // Elastic Net: downward triangle (matches the PNG)
  const OFFSETS = [-0.12, -0.06, 0, 0.06, 0.12];
  const $ = (id) => document.getElementById(id);

  const overall = C.bestOverall(DATA.models);
  const state = { scheme: overall.scheme, k: overall.model.k };
  let rmseChart = null;
  let r2Chart = null;

  const css = (name) => getComputedStyle(document.documentElement).getPropertyValue(name).trim();
  const seriesColor = (i) => css(`--series-${i + 1}`);
  const bestFor = (scheme) => DATA.best.find((b) => b.method === scheme);
  const modelOf = (scheme, k) => DATA.models[scheme].find((m) => m.k === k);

  /** The model shown in the single-model sections (Compare All -> the overall CV-best model). */
  function activeModel() {
    if (state.scheme === ALL) return { scheme: overall.scheme, model: overall.model, viaAll: true };
    return { scheme: state.scheme, model: modelOf(state.scheme, state.k), viaAll: false };
  }

  // ---------- Header ----------
  function renderBadges() {
    const m = DATA.meta;
    $('badges').innerHTML = [
      `<span class="badge">${m.dataset}</span>`,
      `<span class="badge">Train ${m.n_train} / Test ${m.n_test} · random_state ${m.random_state}</span>`,
      '<span class="badge">Nested CV: outer 5 × inner 5</span>',
      `<span class="badge">Best by CV RMSE: <strong>${overall.scheme}, k = ${overall.model.k}</strong> (${C.usd(overall.model.cv_rmse, 2)})</span>`,
    ].join('');
    $('metaLine').textContent = `Generated by analysis/nested_cv_comparison.py · data sha256 ${m.csv_sha256.slice(0, 12)}… · ` +
      Object.entries(m.versions).map(([k, v]) => `${k} ${v}`).join(', ');
    $('rfecvNote').textContent = `on the full training set RFECV picks k = ${DATA.rfecv.k} (${DATA.rfecv.features.join(', ')})`;
  }

  // ---------- Controls ----------
  function renderControls() {
    const schemeBtns = SCHEMES.map((name, i) => {
      const checked = state.scheme === name;
      return `<button type="button" class="seg-btn" role="radio" aria-checked="${checked}" data-scheme="${name}">
        <span class="swatch" style="background:${seriesColor(i)}"></span>${name}</button>`;
    });
    schemeBtns.push(`<button type="button" class="seg-btn" role="radio" aria-checked="${state.scheme === ALL}" data-scheme="${ALL}">Compare all 5</button>`);
    $('schemeButtons').innerHTML = schemeBtns.join('');

    const best = state.scheme === ALL ? null : bestFor(state.scheme).best_k;
    $('kButtons').innerHTML = [1, 2, 3, 4, 5].map((k) => {
      const disabled = state.scheme === ALL ? 'disabled' : '';
      const mark = k === best ? ' <span class="best-mark">★ best by CV</span>' : '';
      return `<button type="button" class="seg-btn" role="radio" ${disabled} aria-checked="${state.scheme !== ALL && state.k === k}" data-k="${k}">k = ${k}${mark}</button>`;
    }).join('');

    $('selectionHint').textContent = state.scheme === ALL
      ? `Comparing all five schemes. The model sections below show the overall CV-best model: ${overall.scheme}, k = ${overall.model.k}.`
      : `${state.scheme}: ★ marks the k with the lowest CV RMSE for this scheme (chosen on training data only).`;
  }

  // ---------- KPI cards ----------
  function kpi(label, value, note) {
    return `<div class="kpi"><p class="kpi-label">${label}</p><p class="kpi-value">${value}</p><p class="kpi-note">${note}</p></div>`;
  }

  function renderKpis() {
    if (state.scheme === ALL) {
      const ranked = [...DATA.best].sort((a, b) => a.cv_rmse - b.cv_rmse);
      const subsets = new Set(DATA.best.map((b) => [...b.features].sort().join('|')));
      $('kpis').innerHTML = [
        kpi('Lowest CV RMSE', C.usd(ranked[0].cv_rmse, 2), `${ranked[0].method}, k = ${ranked[0].best_k}`),
        kpi('Highest CV RMSE (best k)', C.usd(ranked[ranked.length - 1].cv_rmse, 2), `${ranked[ranked.length - 1].method}, k = ${ranked[ranked.length - 1].best_k}`),
        kpi('Distinct best subsets', String(subsets.size), 'across the five schemes'),
        kpi('RFECV (automatic k)', `k = ${DATA.rfecv.k}`, DATA.rfecv.features.join(', ')),
      ].join('');
      return;
    }
    const m = modelOf(state.scheme, state.k);
    $('kpis').innerHTML = [
      kpi('CV RMSE', C.usd(m.cv_rmse, 2), `fold SD ${C.usd(C.std(m.fold_rmse), 0)} · 5 outer folds`),
      kpi('CV R²', C.num(m.cv_r2, 4), 'mean of outer folds'),
      kpi('Fold agreement', `${m.folds_agree} / 5`, 'outer folds that picked the final subset'),
      kpi('Selected features', `k = ${m.k}`, m.features.join(', ')),
      kpi('Train fit (OLS)', `Adj. R² ${C.num(m.train_adj_r2, 4)}`, `F = ${C.num(m.f_stat, 1)}, p ${C.pValue(m.f_pvalue)}`),
    ].join('');
  }

  // ---------- Charts ----------
  function chartData(metric) {
    return SCHEMES.map((name, i) => {
      const faded = state.scheme !== ALL && state.scheme !== name;
      const color = seriesColor(i);
      const list = DATA.models[name];
      const current = state.scheme === name ? state.k : null;
      return {
        label: name,
        data: list.map((m) => ({ x: m.k + OFFSETS[i], y: m[metric], k: m.k })),
        borderColor: faded ? color + '40' : color,
        backgroundColor: faded ? color + '40' : color,
        pointStyle: POINT_STYLES[i],
        rotation: POINT_ROTATION[i],
        borderWidth: faded ? 1.5 : 2.5,
        pointRadius: list.map((m) => (m.k === current ? 9 : 5)),
        pointHoverRadius: 9,
        pointBorderColor: css('--surface-1'),
        pointBorderWidth: 2,
        order: faded ? 1 : 0,
      };
    });
  }

  function chartOptions(title, yLabel, isRmse) {
    const text = css('--text-secondary');
    const grid = css('--grid');
    return {
      responsive: true,
      maintainAspectRatio: false,
      animation: false,
      interaction: { mode: 'index', intersect: false },
      plugins: {
        title: { display: true, text: title, color: css('--text-primary'), font: { size: 14, weight: '600' } },
        legend: {
          position: 'bottom',
          labels: {
            color: text, usePointStyle: true, boxWidth: 8, padding: 14,
            sort: (a, b) => a.datasetIndex - b.datasetIndex,   // fixed order: colour follows the scheme
          },
        },
        tooltip: {
          callbacks: {
            title: (items) => `k = ${items[0].raw.k}`,
            label: (item) => {
              const m = modelOf(item.dataset.label, item.raw.k);
              const value = isRmse ? C.usd(item.raw.y, 2) : C.num(item.raw.y, 4);
              return `${item.dataset.label}: ${value} — ${m.features.join(', ')} (${m.folds_agree}/5 folds agree)`;
            },
          },
        },
      },
      scales: {
        x: {
          type: 'linear', min: 0.6, max: 5.4,
          title: { display: true, text: 'Number of features (k)', color: text },
          ticks: { color: text, autoSkip: false },
          afterBuildTicks: (axis) => { axis.ticks = [1, 2, 3, 4, 5].map((value) => ({ value })); },
          grid: { color: grid },
        },
        y: {
          title: { display: true, text: yLabel, color: text },
          ticks: { color: text, callback: (v) => (isRmse ? C.usd(v, 0) : C.num(v, 3)) },
          grid: { color: grid },
        },
      },
    };
  }

  function renderCharts() {
    if (typeof Chart === 'undefined') {
      $('rmseChart').parentElement.innerHTML = '<p class="sub">Chart.js could not be loaded (offline?). The same numbers are in the "All 25 results" table below.</p>';
      $('r2Chart').parentElement.style.display = 'none';
      return;
    }
    const specs = [
      ['rmseChart', 'cv_rmse', 'CV RMSE vs. number of features', 'CV RMSE (USD, lower is better)', true],
      ['r2Chart', 'cv_r2', 'CV R² vs. number of features', 'CV R² (higher is better)', false],
    ];
    specs.forEach(([id, metric, title, yLabel, isRmse]) => {
      const config = { type: 'line', data: { datasets: chartData(metric) }, options: chartOptions(title, yLabel, isRmse) };
      const existing = id === 'rmseChart' ? rmseChart : r2Chart;
      if (existing) existing.destroy();
      const chart = new Chart($(id), config);
      if (id === 'rmseChart') rmseChart = chart; else r2Chart = chart;
    });
  }

  // ---------- Model sections ----------
  function renderModel() {
    const { scheme, model, viaAll } = activeModel();
    $('eqSub').textContent = `${viaAll ? 'Overall CV-best model: ' : ''}${scheme}, k = ${model.k}. ` +
      'Coefficients, standard errors, t-tests and VIF come from OLS on all 40 training rows.';
    $('equation').textContent = C.equation(model);
    $('coefTable').querySelector('tbody').innerHTML = model.coefficients.map((c) => {
      const d = c.feature === 'Intercept' ? 2 : 4;          // the intercept is in dollars
      return `<tr>
        <td>${c.feature}</td><td>${C.num(c.coef, d)}</td>
        <td>${C.num(c.stderr, d)}</td><td>${C.num(c.tstat, 2)}</td><td>${C.pValue(c.pvalue)}</td>
        <td>[${C.num(c.ci_lower, d)}, ${C.num(c.ci_upper, d)}]</td>
        <td>${c.vif === null ? '—' : C.num(c.vif, 2)}</td></tr>`;
    }).join('');
    $('fitStats').textContent = `Train R² ${C.num(model.train_r2, 4)} · Adj. R² ${C.num(model.train_adj_r2, 4)} · ` +
      `F = ${C.num(model.f_stat, 1)} (p ${C.pValue(model.f_pvalue)}) · residual df ${model.df_resid}.`;
    renderPrediction();
  }

  function readInputs() {
    return {
      'R&D Spend': Number($('inRD').value),
      Administration: Number($('inAdmin').value),
      'Marketing Spend': Number($('inMkt').value),
      state: $('inState').value,
    };
  }

  function renderPrediction() {
    const { scheme, model } = activeModel();
    const out = C.predict(model, readInputs());
    $('predValue').textContent = C.usd(out.prediction, 2);
    $('predInterval').textContent = `95% prediction interval: ${C.usd(out.lower, 0)} to ${C.usd(out.upper, 0)}`;
    $('predContrib').innerHTML = [`<li>Intercept: ${C.usd(out.intercept, 0)}</li>`,
      ...out.contributions.map((c) => `<li>${c.feature}: ${c.contribution < 0 ? '' : '+'}${C.usd(c.contribution, 0)}</li>`)].join('');
    const unused = ['R&D Spend', 'Administration', 'Marketing Spend', 'State']
      .filter((f) => !model.features.some((mf) => mf === f || (f === 'State' && mf.startsWith('State_'))));
    $('predNote').textContent = `Model: ${scheme}, k = ${model.k}.` + (unused.length ? ` Not used by this model: ${unused.join(', ')}.` : '');
  }

  // ---------- Tables ----------
  function renderBestTable() {
    const current = activeModel().scheme;
    $('bestTable').querySelector('tbody').innerHTML = DATA.best.map((b) => {
      const i = SCHEMES.indexOf(b.method);
      return `<tr class="${b.method === current ? 'is-current' : ''}">
        <td><span class="tag"><span class="swatch" style="background:${seriesColor(i)}"></span>${b.method}</span></td>
        <td>${b.best_k}</td><td class="wrap-cell">${b.features.join(', ')}</td>
        <td>${C.usd(b.cv_rmse, 2)}</td><td>${C.num(b.cv_r2, 4)}</td>
        <td>${C.usd(b.test_mae, 2)}</td><td>${Math.round(b.test_mse).toLocaleString('en-US')}</td>
        <td>${C.usd(b.test_rmse, 2)}</td><td>${C.num(b.test_r2, 4)}</td></tr>`;
    }).join('');
  }

  function renderTestTable() {
    const scheme = activeModel().scheme;
    const b = bestFor(scheme);
    const covered = b.test_predictions.filter((p) => p.covered).length;
    $('testSub').textContent = `${scheme} at its best k = ${b.best_k} (${b.features.join(', ')}). ` +
      `${covered} of ${b.test_predictions.length} actual profits fall inside the 95% prediction interval. ` +
      'Rows are sorted by absolute residual.';
    const rows = [...b.test_predictions].sort((a, c) => Math.abs(c.residual) - Math.abs(a.residual));
    $('testTable').querySelector('tbody').innerHTML = rows.map((p) => `<tr>
        <td>${p.row}</td><td>${C.usd(p.actual, 2)}</td><td>${C.usd(p.predicted, 2)}</td>
        <td>${C.usd(p.residual, 2)}</td><td>${C.usd(p.pi_lower, 0)} – ${C.usd(p.pi_upper, 0)}</td>
        <td><span class="status ${p.covered ? 'ok' : 'no'}">${p.covered ? '✓ yes' : '✗ no'}</span></td></tr>`).join('');
  }

  function renderAllTable() {
    $('allTable').querySelector('tbody').innerHTML = SCHEMES.flatMap((name) => DATA.models[name].map((m) => `
      <tr class="${state.scheme === name && state.k === m.k ? 'is-current' : ''}">
        <td>${name}</td><td>${m.k}</td><td class="wrap-cell">${m.features.join(', ')}</td>
        <td>${C.usd(m.cv_rmse, 2)}</td><td>${C.num(m.cv_r2, 4)}</td><td>${m.folds_agree} / 5</td></tr>`)).join('');
  }

  function renderAll() {
    renderControls();
    renderKpis();
    renderCharts();
    renderModel();
    renderBestTable();
    renderTestTable();
    renderAllTable();
  }

  // ---------- Events ----------
  function setupEvents() {
    $('schemeButtons').addEventListener('click', (e) => {
      const btn = e.target.closest('[data-scheme]');
      if (!btn) return;
      state.scheme = btn.dataset.scheme;
      if (state.scheme !== ALL) state.k = bestFor(state.scheme).best_k;
      renderAll();
    });
    $('kButtons').addEventListener('click', (e) => {
      const btn = e.target.closest('[data-k]');
      if (!btn || btn.disabled) return;
      state.k = Number(btn.dataset.k);
      renderAll();
    });
    ['inRD', 'inAdmin', 'inMkt', 'inState'].forEach((id) => $(id).addEventListener('input', renderPrediction));
    $('themeToggle').addEventListener('click', () => {
      const dark = css('color-scheme') === 'dark';
      document.documentElement.dataset.theme = dark ? 'light' : 'dark';
      try { localStorage.setItem('dic02-theme', document.documentElement.dataset.theme); } catch (err) { /* storage unavailable */ }
      renderAll();
    });
  }

  function init() {
    try {
      const saved = localStorage.getItem('dic02-theme');
      if (saved === 'light' || saved === 'dark') document.documentElement.dataset.theme = saved;
    } catch (err) { /* storage unavailable */ }
    // Optional deep link: ?scheme=<name>|all&k=<1-5>
    const params = new URLSearchParams(location.search);
    const wanted = params.get('scheme');
    if (wanted && wanted.toLowerCase() === 'all') state.scheme = ALL;
    else if (wanted && SCHEMES.includes(wanted)) {
      state.scheme = wanted;
      const k = Number(params.get('k'));
      state.k = k >= 1 && k <= 5 ? k : bestFor(wanted).best_k;
    }
    const r = DATA.input_ranges;
    $('inRD').value = Math.round(r['R&D Spend'].median);
    $('inAdmin').value = Math.round(r.Administration.median);
    $('inMkt').value = Math.round(r['Marketing Spend'].median);
    renderBadges();
    setupEvents();
    renderAll();
  }

  init();
})();
